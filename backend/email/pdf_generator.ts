// backend/email/pdf_generator.ts

import PDFDocument from 'pdfkit';
import axios from 'axios';

/**
 * PDF Dossier Generator — PRD Section 5
 *
 * Generates a 5-page classified-style intelligence report from a consolidated dossier.
 *
 * @param dossier - Consolidated email or telephone scan dossier
 * @returns PDF buffer
 */
export async function generateDossierPDF(dossier: any): Promise<Buffer> {
  let avatarBuffer: Buffer | null = null;
  const isPhone = !!dossier.phone;

  if (isPhone) {
    try {
      const cleanPhone = dossier.phone.trim().replace(/\s+/g, '');
      const rawDigits = cleanPhone.replace('+', '');
      const avatarUrl = `https://i.pravatar.cc/150?u=${rawDigits}`;
      const imgRes = await axios.get(avatarUrl, {
        responseType: 'arraybuffer',
        timeout: 2500
      });
      if (imgRes.status === 200) {
        avatarBuffer = Buffer.from(imgRes.data);
      }
    } catch {
      // Safe fallback — ignore timeout/error
    }
  } else if (dossier.gravatar && dossier.gravatar.avatarUrl) {
    try {
      const imgRes = await axios.get(dossier.gravatar.avatarUrl, {
        responseType: 'arraybuffer',
        timeout: 2500
      });
      if (imgRes.status === 200) {
        avatarBuffer = Buffer.from(imgRes.data);
      }
    } catch {
      // Safe fallback
    }
  }

  return new Promise<Buffer>((resolve, reject) => {
    const targetTitle = isPhone ? maskPhone(dossier.phone) : maskEmail(dossier.email);

    const doc = new PDFDocument({
      size: 'A4',
      margins: { top: 50, bottom: 50, left: 60, right: 60 },
      info: {
        Title: 'OSINT Intelligence Dossier',
        Author: 'Antigravity OSINT Suite',
        Subject: `Digital Footprint Analysis: ${targetTitle}`,
      },
    });

    const chunks: Buffer[] = [];
    doc.on('data', (chunk: any) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    if (isPhone) {
      // ─── PAGE 1: COVER ───
      renderPhoneCover(doc, dossier);

      // ─── PAGE 2: SUBJECT PROFILE ───
      doc.addPage();
      renderPhoneSubjectProfile(doc, dossier, avatarBuffer);

      // ─── PAGE 3: OTT & SOCIAL ACCOUNTS ───
      doc.addPage();
      renderPhoneSocialAccounts(doc, dossier);
    } else {
      // ─── PAGE 1: COVER ───
      renderCover(doc, dossier);

      // ─── PAGE 2: SUBJECT PROFILE ───
      doc.addPage();
      renderSubjectProfile(doc, dossier, avatarBuffer);

      // ─── PAGE 3: PLATFORM FINDINGS ───
      doc.addPage();
      renderPlatformFindings(doc, dossier);

      // ─── PAGE 4: BREACH DETAILS ───
      doc.addPage();
      renderBreachDetails(doc, dossier);

      // ─── PAGE 5: APPENDIX ───
      doc.addPage();
      renderAppendix(doc, dossier);
    }

    doc.end();
  });
}

// ─── Page Renderers ───

function renderCover(doc: typeof PDFDocument | any, dossier: any) {
  doc.moveDown(6);

  // Classified banner
  doc.fontSize(14).font('Helvetica-Bold').fillColor('#cc0000')
    .text('████ TOP SECRET ████', { align: 'center' });
  doc.moveDown(0.5);

  doc.fontSize(22).font('Helvetica-Bold').fillColor('#1a1a2e')
    .text('CLASSIFIED INVESTIGATION', { align: 'center' });
  doc.moveDown(0.3);

  doc.fontSize(16).fillColor('#333')
    .text('DIGITAL FOOTPRINT ANALYSIS', { align: 'center' });
  doc.moveDown(2);

  doc.fontSize(12).font('Helvetica').fillColor('#555')
    .text(`Target: ${maskEmail(dossier.email)}`, { align: 'center' });
  doc.moveDown(0.5);
  doc.text(`Date: ${new Date().toISOString().replace('T', ' ').slice(0, 19)} UTC`, { align: 'center' });
  doc.moveDown(0.5);
  doc.text(`Analysis Duration: ${dossier.timeTakenMs}ms`, { align: 'center' });

  doc.moveDown(4);

  // Footer line
  doc.fontSize(8).fillColor('#999')
    .text('Generated by Antigravity OSINT Intelligence Suite', { align: 'center' });
  doc.text('For authorized use only. Handle according to classification level.', { align: 'center' });
}

function renderSubjectProfile(doc: typeof PDFDocument | any, dossier: any, avatarBuffer: Buffer | null = null) {
  doc.fontSize(16).font('Helvetica-Bold').fillColor('#1a1a2e')
    .text('SUBJECT PROFILE', { align: 'left' });
  doc.moveDown(0.5);
  drawHR(doc);
  doc.moveDown(1);

  const identity = dossier.identity || {};
  const gravatar = dossier.gravatar || {};

  // Draw Avatar Box on top right dynamically if possible
  const currentY = doc.y;
  if (avatarBuffer) {
    try {
      // Rounded border rect
      doc.lineWidth(2).strokeColor('#0066cc').rect(438, currentY - 2, 94, 94).stroke();
      doc.image(avatarBuffer, 440, currentY, { width: 90, height: 90 });
    } catch {
      // Graceful fallback to placeholder box
      doc.lineWidth(1).strokeColor('#888').dash(3, { space: 3 }).rect(440, currentY, 90, 90).stroke();
      doc.fontSize(16).fillColor('#888').text('👤', 472, currentY + 35);
      doc.undash();
    }
  } else if (gravatar.hasGravatar) {
    doc.lineWidth(1).strokeColor('#888').dash(3, { space: 3 }).rect(440, currentY, 90, 90).stroke();
    doc.fontSize(22).fillColor('#888').text('👤', 470, currentY + 30);
    doc.undash();
  }

  // Restore doc text position to align nicely with avatar
  doc.y = currentY;

  const fields = [
    ['Email', dossier.email],
    ['Real Name', identity.realName || 'Not Resolved'],
    ['Employer', identity.employer || 'Unknown'],
    ['Position', identity.position || 'Unknown'],
    ['Confidence', identity.confidence || 'LOW'],
    ['Gravatar', gravatar.hasGravatar ? 'Found' : 'Not Found'],
    ['Breach Count', `${(dossier.breaches || []).length} breach(es)`],
    ['Sources', (identity.sources || []).join(', ') || 'None'],
  ];

  doc.fontSize(11).font('Helvetica');
  for (const [label, value] of fields) {
    doc.fillColor('#555').text(`${label}:`, { continued: true });
    doc.fillColor('#1a1a2e').text(`  ${value}`, { width: 350 });
    doc.moveDown(0.35);
  }

  if (gravatar.avatarUrl) {
    doc.moveDown(1.5);
    doc.fontSize(9).fillColor('#888').text(`Avatar Source URL: ${gravatar.avatarUrl}`);
  }
}

function renderPlatformFindings(doc: typeof PDFDocument | any, dossier: any) {
  doc.fontSize(16).font('Helvetica-Bold').fillColor('#1a1a2e')
    .text('PLATFORM FINDINGS', { align: 'left' });
  doc.moveDown(0.5);
  drawHR(doc);
  doc.moveDown(1);

  const usernames = dossier.usernames || {};

  doc.fontSize(11).font('Helvetica').fillColor('#333');
  doc.text(`Primary Username: ${usernames.primary || 'N/A'}`);
  doc.moveDown(0.3);
  doc.text(`Variants Searched: ${(usernames.variants || []).join(', ') || 'None'}`);
  doc.moveDown(1);

  // Platform scan results table (if platformResults exist on dossier)
  if (dossier.platformResults && dossier.platformResults.length > 0) {
    doc.fontSize(10).font('Helvetica-Bold');
    doc.text('Platform', 60, doc.y, { width: 120 });
    doc.text('Status', 180, doc.y, { width: 80 });
    doc.text('URL', 260, doc.y, { width: 250 });
    doc.moveDown(0.5);
    drawHR(doc);

    doc.font('Helvetica').fontSize(9);
    for (const result of dossier.platformResults) {
      if (doc.y > 750) {
        doc.addPage();
      }
      const statusColor = result.status === 'FOUND' ? '#00aa55' : '#999';
      doc.fillColor('#333').text(result.platform, 60, doc.y, { width: 120 });
      doc.fillColor(statusColor).text(result.status, 180, doc.y, { width: 80 });
      doc.fillColor('#555').text(result.url || '', 260, doc.y, { width: 250 });
      doc.moveDown(0.3);
    }
  } else {
    doc.fontSize(10).fillColor('#888')
      .text('No platform scan results included in this dossier.');
  }
}

function renderBreachDetails(doc: typeof PDFDocument | any, dossier: any) {
  doc.fontSize(16).font('Helvetica-Bold').fillColor('#1a1a2e')
    .text('BREACH DETAILS', { align: 'left' });
  doc.moveDown(0.5);
  drawHR(doc);
  doc.moveDown(1);

  const breaches = dossier.breaches || [];

  if (breaches.length === 0) {
    doc.fontSize(11).font('Helvetica').fillColor('#888')
      .text('No known breaches found for this email address.');
    return;
  }

  for (const breach of breaches) {
    if (doc.y > 700) {
      doc.addPage();
    }

    doc.fontSize(12).font('Helvetica-Bold').fillColor('#cc0000')
      .text(breach.name || 'Unknown Breach');
    doc.fontSize(10).font('Helvetica').fillColor('#555');
    doc.text(`Domain: ${breach.domain || 'N/A'} | Date: ${breach.breachDate || 'Unknown'} | Records: ${formatNumber(breach.pwnCount)}`);
    doc.moveDown(0.3);
    doc.text(`Compromised Data: ${(breach.compromisedData || []).join(', ')}`);
    doc.moveDown(0.3);

    if (breach.description) {
      // Strip HTML tags from description
      const cleanDesc = breach.description.replace(/<[^>]*>/g, '');
      doc.fontSize(9).fillColor('#666').text(cleanDesc, { width: 460 });
    }

    doc.moveDown(1);
  }
}

