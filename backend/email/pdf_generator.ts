// ─── Utilities ───

function drawHR(doc: typeof PDFDocument | any) {
  const y = doc.y;
  doc.moveTo(60, y).lineTo(535, y).strokeColor('#ddd').lineWidth(1).stroke();
  doc.moveDown(0.3);
}

export function maskEmail(email: string): string {
  if (!email || !email.includes('@')) return email || 'N/A';
  const [local, domain] = email.split('@');
  if (local.length <= 3) return `${local[0]}***@${domain}`;
  return `${local.slice(0, 3)}***@${domain}`;
}

export function maskPhone(phone: string): string {
  if (!phone) return 'N/A';
  const clean = phone.trim().replace(/\s+/g, '').replace(/[\(\)\-]/g, '');

  let countryCode = '';
  let local = clean;

  if (clean.startsWith('+')) {
    // Dynamic matching of popular country code lengths: 1, 2, or 3 digits
    if (clean.startsWith('+84') || clean.startsWith('+44') || clean.startsWith('+61') || clean.startsWith('+81')) {
      countryCode = clean.slice(0, 3);
      local = clean.slice(3);
    } else if (clean.startsWith('+1')) {
      countryCode = clean.slice(0, 2);
      local = clean.slice(2);
    } else {
      const match = clean.match(/^\+(\d{1,3})/);
      if (match) {
        countryCode = match[0];
        local = clean.slice(countryCode.length);
      }
    }
  }

  if (local.length >= 6) {
    const prefixLen = Math.min(3, Math.floor(local.length / 3));
    const suffixLen = Math.min(3, Math.floor(local.length / 3));
    const maskLen = local.length - prefixLen - suffixLen;
    const maskStr = '*'.repeat(maskLen);
    return `${countryCode} ${local.slice(0, prefixLen)} ${maskStr} ${local.slice(-suffixLen)}`.trim();
  }

  if (clean.length > 6) {
    return `${clean.slice(0, 3)} *** ${clean.slice(-3)}`;
  }
  return clean;
}

function formatNumber(num: number): string {
  if (!num) return '0';
  return num.toLocaleString('en-US');
}
